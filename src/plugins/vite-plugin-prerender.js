import fs from "fs";
import path from "path";
import { pathToFileURL } from "url";

/**
 * Vite plugin (build-only): prerenders per-route HTML shells with correct
 * SEO meta so that social crawlers and search engines — which do NOT run
 * JavaScript — see real titles, descriptions, Open Graph tags, canonical
 * URLs and JSON-LD for every page.
 *
 * How it works:
 *   1. Runs in `closeBundle`, after Vite has written dist/.
 *   2. Reads dist/index.html (the built SPA shell) as a template.
 *   3. For every static route + every post/note route, replaces <title> and
 *      meta description, injects og/twitter/canonical/JSON-LD tags, and
 *      writes dist/<route>/index.html.
 *   4. GitHub Pages serves these physical files directly, so deep links
 *      work with BrowserRouter — no 404.html redirect hack needed.
 *   5. Also writes dist/404.html (SPA shell with noindex) for unknown paths.
 *
 * Post data is loaded via dynamic import() of the generated ESM data files
 * (with cache-busting query) — no fragile regex parsing of our own output.
 */
export function prerenderMetaPlugin({
  siteUrl = "https://xdcr.de5.net",
  siteName = "Canvas & Code",
  defaultDescription = "Canvas & Code — A blog about engineering, design, and the craft of building things with warmth and intention.",
} = {}) {
  const root = process.cwd();
  const distDir = path.resolve(root, "dist");
  const base = siteUrl.replace(/\/$/, "");

  // Meta for static routes — mirrors the <SEO> props used by each page
  // component (English values; <html lang="en"> is the site default).
  // URLs use trailing slashes: GitHub Pages serves directories at the
  // slash-suffixed URL (301 from the bare path), so canonical = final URL.
  const staticRoutes = [
    { path: "/", url: "/", title: "", description: defaultDescription },
    { path: "/blog", url: "/blog/", title: "Blog", description: "Thoughts on code, design, creativity, and the things in between." },
    { path: "/notes", url: "/notes/", title: "Notes", description: "A collection of knowledge points, insights, and quick thoughts organized by topic." },
    { path: "/tags", url: "/tags/", title: "Tags", description: "Browse all posts and notes by tag" },
    { path: "/series", url: "/series/", title: "Series", description: "Ongoing article series by topic" },
    { path: "/links", url: "/links/", title: "Friend Links", description: "Blogs I admire and friends" },
    { path: "/guestbook", url: "/guestbook/", title: "Guestbook", description: "Leave your footprints here" },
    { path: "/about", url: "/about/", title: "About", description: "A little about who I am and why I write." },
    { path: "/archive", url: "/archive/", title: "Archive", description: "Timeline archive of all posts and notes" },
    { path: "/projects", url: "/projects/", title: "Projects", description: "My personal projects and open-source work" },
    { path: "/changelog", url: "/changelog/", title: "Changelog", description: "Site feature iterations and update history" },
  ];

  // ── Helpers ─────────────────────────────────────────────

  function escapeHtml(str) {
    return String(str ?? "")
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;");
  }

  function stripMarkdown(md) {
    if (!md) return "";
    return md
      .replace(/```[\s\S]*?```/g, "")
      .replace(/`[^`]*`/g, "")
      .replace(/!\[.*?\]\(.*?\)/g, "")
      .replace(/\[([^\]]*)\]\(.*?\)/g, "$1")
      .replace(/<[^>]+>/g, "")
      .replace(/[#>*_\-|]/g, " ")
      .replace(/\s+/g, " ")
      .trim();
  }

  function truncate(str, max = 160) {
    if (!str) return "";
    return str.length > max ? str.slice(0, max - 1).trimEnd() + "…" : str;
  }

  function absoluteUrl(urlOrPath) {
    if (!urlOrPath) return "";
    if (/^https?:\/\//.test(urlOrPath)) return urlOrPath;
    return `${base}${urlOrPath.startsWith("/") ? "" : "/"}${urlOrPath}`;
  }

  /** Load an ESM data file generated by blog-content plugin (cache-busted). */
  async function loadGenerated(filePath, exportName) {
    if (!fs.existsSync(filePath)) return [];
    try {
      const mod = await import(`${pathToFileURL(filePath).href}?t=${Date.now()}`);
      return Array.isArray(mod[exportName]) ? mod[exportName] : [];
    } catch (err) {
      console.warn(`[prerender] Failed to load ${path.basename(filePath)}: ${err.message}`);
      return [];
    }
  }

  // ── Meta → HTML ─────────────────────────────────────────

  /**
   * Build the <head> tag list for a page.
   * @param {object} m
   * @param {string} m.title — page title without site name ("" for home)
   * @param {string} m.description
   * @param {string} m.url — absolute canonical URL
   * @param {string} [m.type] — og:type ("website" | "article")
   * @param {string} [m.image] — absolute og:image URL
   * @param {string} [m.publishedTime] — ISO date for article:published_time
   */
  function buildMeta({ title, description, url, type = "website", image = "", publishedTime = "" }) {
    const fullTitle = title ? `${title} — ${siteName}` : siteName;
    const desc = description || defaultDescription;
    const tags = [
      `<link rel="canonical" href="${escapeHtml(url)}" />`,
      `<meta property="og:site_name" content="${escapeHtml(siteName)}" />`,
      `<meta property="og:title" content="${escapeHtml(title || siteName)}" />`,
      `<meta property="og:description" content="${escapeHtml(desc)}" />`,
      `<meta property="og:type" content="${type}" />`,
      `<meta property="og:url" content="${escapeHtml(url)}" />`,
    ];
    if (image) tags.push(`<meta property="og:image" content="${escapeHtml(image)}" />`);
    if (publishedTime) tags.push(`<meta property="article:published_time" content="${escapeHtml(publishedTime)}" />`);
    tags.push(`<meta name="twitter:card" content="${image ? "summary_large_image" : "summary"}" />`);
    tags.push(`<meta name="twitter:title" content="${escapeHtml(title || siteName)}" />`);
    tags.push(`<meta name="twitter:description" content="${escapeHtml(desc)}" />`);
    if (image) tags.push(`<meta name="twitter:image" content="${escapeHtml(image)}" />`);
    return { fullTitle, desc, tags };
  }

  /** Inject meta into the built index.html template. */
  function renderPage(template, meta, jsonLd = null, extraHeadTags = []) {
    let html = template;
    html = html.replace(
      /<title>[\s\S]*?<\/title>/,
      `<title>${escapeHtml(meta.fullTitle)}</title>`
    );
    html = html.replace(
      /<meta\s+name="description"\s+content="[^"]*"\s*\/?>/,
      `<meta name="description" content="${escapeHtml(meta.desc)}" />`
    );
    const allTags = [...meta.tags, ...extraHeadTags];
    // Escape "<" in JSON-LD so a "</script>" sequence in content can't break out
    if (jsonLd) {
      allTags.push(
        `<script type="application/ld+json">${JSON.stringify(jsonLd).replace(/</g, "\\u003c")}</script>`
      );
    }
    html = html.replace("</head>", `    ${allTags.join("\n    ")}\n  </head>`);
    return html;
  }

  function writeRoute(routePath, html) {
    const outFile =
      routePath === "/"
        ? path.join(distDir, "index.html")
        : path.join(distDir, routePath.slice(1), "index.html");
    fs.mkdirSync(path.dirname(outFile), { recursive: true });
    fs.writeFileSync(outFile, html, "utf-8");
  }

  // ── Plugin ──────────────────────────────────────────────

  return {
    name: "prerender-meta",
    apply: "build",
    async closeBundle() {
      const templatePath = path.join(distDir, "index.html");
      if (!fs.existsSync(templatePath)) {
        console.warn("[prerender] dist/index.html not found, skipping.");
        return;
      }
      const template = fs.readFileSync(templatePath, "utf-8");

      const posts = await loadGenerated(path.resolve(root, "src/generated/posts-data.js"), "posts");
      const notes = await loadGenerated(path.resolve(root, "src/generated/notes-data.js"), "notes");

      let count = 0;

      // Static routes
      for (const r of staticRoutes) {
        const meta = buildMeta({ ...r, url: `${base}${r.url}` });
        writeRoute(r.path, renderPage(template, meta));
        count++;
      }

      // Post routes — with article JSON-LD. Canonical uses trailing slash,
      // matching the URL GitHub Pages finally serves (301 from bare path).
      for (const post of posts) {
        const url = `${base}/post/${post.slug}/`;
        const desc = truncate(post.excerpt || stripMarkdown(post.content));
        const image = absoluteUrl(post.coverImage);
        const meta = buildMeta({
          title: post.title,
          description: desc,
          url,
          type: "article",
          image,
          publishedTime: post.date || "",
        });
        const jsonLd = {
          "@context": "https://schema.org",
          "@type": "Article",
          headline: post.title,
          description: desc,
          ...(image ? { image: [image] } : {}),
          ...(post.date ? { datePublished: post.date } : {}),
          mainEntityOfPage: url,
          author: { "@type": "Organization", name: siteName },
          publisher: { "@type": "Organization", name: siteName },
        };
        writeRoute(`/post/${post.slug}`, renderPage(template, meta, jsonLd));
        count++;
      }

      // Note routes
      for (const note of notes) {
        const url = `${base}/note/${note.slug}/`;
        const desc = truncate(stripMarkdown(note.content));
        const meta = buildMeta({
          title: note.title,
          description: desc,
          url,
          type: "article",
          publishedTime: note.date || "",
        });
        writeRoute(`/note/${note.slug}`, renderPage(template, meta));
        count++;
      }

      // 404 shell — GitHub Pages serves this for unknown paths; the SPA
      // boots and shows its own NotFound page. Marked noindex.
      const notFoundMeta = buildMeta({
        title: "404",
        description: "Page not found",
        url: `${base}/`,
      });
      fs.writeFileSync(
        path.join(distDir, "404.html"),
        renderPage(template, notFoundMeta, null, [`<meta name="robots" content="noindex" />`]),
        "utf-8"
      );

      console.log(`[prerender] Generated ${count} route HTML files + 404.html → ${path.relative(root, distDir)}`);
    },
  };
}
